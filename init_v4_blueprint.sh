## 🧩 الهيكل العام لـ 6 كروت الواجهة الرئيسية

### 1. كارت الترجمات النصية (Text Translation)
* **أعلى الشاشة:** زر منتصف لاختيار اللغة (دعم +100 لغة)، يحفظ آخر لغة مختارة تلقائياً.
* **محرر إدخال علوي:** يحتوي على مايكروفون لالتقاط الصوت الفعلي عبر التسجيل، وتحرير النص للتحقق وتعديله.
* **محرر إخراج سفلي:** يُظهر ترجمة النص فوراً.
* **أداة رفع ملف صوتي (دبوس):** لرفع وتفريغ وترجمة الملفات الصوتية حتى 16MB.
* **زر النسخ والمشاركة الصوتية:** لنسخ الترجمة أو استماعها.

### 2. كارت الحوار المترجم (Interactive Conversation)
* **محرران متقابلان:** إدخال وإخراج مع مساحة واسعة ومتابعة الحوار.
* **شريط التحكم السفلي:** زر اختيار اللغة يميناً ويساراً مع سهم التبديل، ومايكروفون تفاعلي لتسجيل الحوار وترجمته.

### 3. كارت ترجمة المستندات والعدسة (Documents & Google Lens)
* **زر العدسة (Google Lens):** فحص بصري واستخراج النصوص (OCR) عبر نموذج ذكاء متعدد الوسائط.
* **زر المستندات:** مستطيل إدخال رابط مع زر بحث / زر فتح مستعرض الجهاز، وترجمة المستندات PDF/صور مع عرض مزدوج (الأصلي والترجمة).

### 4. كارت القصص والإلهام وأسباب النزول (Stories & Inspiration)
* **المحتوى أوف لاين:** أحاديث قدسية، قصص الأنبياء، وقصص الأقوام مخزنة محلياً.
* **فهرس المصادر السحابية:** تنزيل النصوص وتخزينها محلياً مع إسناد المصدر.
* **رسائل الإلهام وسيناريو الفيديو:** توليد إلهام يومي وتحويل القصص إلى سيناريو وثائقي طويل عبر الذكاء الاصطناعي مع حواجز أمان صارمة (لا عنف، لا تنمر، لا ألفاظ بذيئة).

### 5. كارت الألعاب 3D (Games Corner)
* **شطرنج 3D:** لوحة ثلاثية الأبعاد تفاعلية مع محرك كمبيوتر ومؤقت لعب (Chess Clock).
* **مكعب روبيك 3D:** مكعب تفاعلي مع خوارزمية حل تلقائي لتعزيز مهارات التفكير.

### 6. كارت الإعدادات والخدمات (Settings)
* **الوضع المظلم الملكي (Royal Dark).**
* **تنزيل اللغات أوف لاين:** مع شريط تقدم ونسبة مئوية واضحة وحالة الحفظ.
* **النسخة البرو (Pro):** تفعيل، معرف الجهاز، وطرق التواصل الرسمية (البريد، التليجرام، واتساب).

