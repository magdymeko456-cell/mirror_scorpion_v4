#!/bin/bash
# ==============================================================================
# Mirror Scorpion v4 - Termux Setup & Synchronization Script
# ------------------------------------------------------------------------------
# الهدف: تجهيز أو مزامنة مستودع mirror_scorpion_v4 محلياً عبر Termux
#        مع دمج الوصف الشامل للكروت الستة، الهوية الملكية، والربط مع GitHub Actions.
# ==============================================================================
set -Eeuo pipefail

WORKDIR="${MIRROR_WORKDIR:-$HOME/mirror_scorpion_v4}"

echo "=== 1/2. التحقق من مسار العمل وتجهيز الهيكل الآمن ==="
if [ ! -d "$WORKDIR" ]; then
    mkdir -p "$WORKDIR"
    echo "تم إنشاء مجلد العمل: $WORKDIR"
else
    echo "مجلد العمل موجود بالفعل: $WORKDIR"
fi
cd "$WORKDIR"

# التأكد من وجود مستودع Git أو تهيئته بلطف
if [ ! -d ".git" ]; then
    git init -b main
    echo "تم تهيئة مستودع Git محلي برئيسية main."
else
    echo "مستودع Git منسق ومفعل."
fi

if ! git config user.name >/dev/null 2>&1 || ! git config user.email >/dev/null 2>&1; then
    echo "خطأ: اضبط هوية Git مرة واحدة قبل تشغيل السكربت:"
    echo '  git config --global user.name "اسمك"'
    echo '  git config --global user.email "بريدك@example.com"'
    exit 1
fi

echo "=== 2/2. تحديث وثيقة الوصف الشامل والبوصلة (README.md) ==="
cat << 'README_EOF' > README.md
# Mirror Scorpion v4 - المِرآة (حيث تُصنع البدايات)

> **المطور:** Tamer Eldosoky
> **نبذة عن التطبيق:** الوقت هو العملة الأغلى التي مُنحت للإنسان. هنا، نحن لا نقيس أعمارنا بالسنوات، بل بكل ثانية نصنع فيها إنجازاً حقيقياً. تذكّر دائماً.. قصتك لا تزال تُكتب، والنهاية لم يحن وقتها بعد.

---

## 📜 دستور العمل والتطوير (النهائي والمطلق)
1. **الالتزام بالهيكل المرجعي الناجح:** الاعتماد التام على البناء المستقر لـ React Native / Expo SDK 54 مع معايير Royal Dark وتوافقات SDK 34.
2. **منع التعديل العشوائي:** لا إضافة لميزات جديدة إلا بعد دراسة واستخراج المسارات الحقيقية.
3. **التطوير التدريجي (Step-by-Step):** تطبيق تعديل واحد خفيف -> الفحص والبناء -> التأكد من النجاح -> الانتقال للخطوة التالية.
4. **التوافق مع المكتبات الحديثة:** تحديث الكود ليلائم أحدث إصدارات Expo وتجنب أخطاء Gradle وFlutter القديمة.
5. **بيئة الترمكس (Termux):** استخدام الترمكس كواسطة تحرير ونقل فقط، بينما يتم تجميع APK سحابياً عبر GitHub Actions.

